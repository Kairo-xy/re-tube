@Serializable
data class VideoItem(
    val id: String,
    val title: String,
    val uploaderName: String,
    val uploaderId: String = "",
    val uploaderAvatar: String = "",
    val uploaderVerified: Boolean = false,
    val thumbnailUrl: String,
    val durationSeconds: Long,
    val viewCount: Long = 0L,
    val uploadedText: String = "",
    val uploadedTimestamp: Long = 0L,
    val description: String = "",
    val likeCount: Long = 0L,
    val dislikeCount: Long = 0L,
    val subscriberCount: Long = 0L,
    val isShort: Boolean = false,
    val isLive: Boolean = false,
    val category: String = "General",
    val hlsUrl: String? = null,
    val dashUrl: String? = null,
    val videoStreams: List<VideoStream> = emptyList(),
    val audioStreams: List<AudioStream> = emptyList(),
    val subtitleTracks: List<SubtitleTrack> = emptyList(),
    val chapters: List<VideoChapter> = emptyList(),
    val relatedVideos: List<VideoItem> = emptyList()
) {
    fun bestPlayableVideoUrl(preferredQuality: String = "1080p"): String? {
        val progressive = videoStreams.filter { !it.isVideoOnly && it.url.isNotBlank() }
        val exactMatch = progressive.firstOrNull { it.qualityLabel.equals(preferredQuality, ignoreCase = true) }
        if (exactMatch != null) return exactMatch.url
        if (progressive.isNotEmpty()) return progressive.maxByOrNull { it.height }?.url
        if (!hlsUrl.isNullOrBlank()) return hlsUrl
        if (!dashUrl.isNullOrBlank()) return dashUrl
        return videoStreams.firstOrNull { it.url.isNotBlank() }?.url
    }
}

